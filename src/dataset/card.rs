//! The card a shipped folder carries.
//!
//! One function, because the card is generated rather than written: every
//! number it states comes from the manifest built in the same run, so the prose
//! cannot drift from the files beside it.

use std::fmt::Write as _;

use super::Manifest;

/// The markdown card a shipped folder carries. It is generated, so it never
/// drifts from the manifest beside it.
pub fn render(m: &Manifest) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "# {}", m.name);
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "Training pairs mined from the public marketlab news corpus, shipped with the tool that built them."
    );
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "This file is generated by `xcm-mmm dataset build`; edit `src/dataset.rs`, not the card."
    );
    let _ = writeln!(s);
    let _ = writeln!(s, "## What is here");
    let _ = writeln!(s);
    let _ = writeln!(s, "| file | rows | bytes | fnv64 |");
    let _ = writeln!(s, "| --- | --- | --- | --- |");
    for f in &m.files {
        let _ = writeln!(
            s,
            "| `{}` | {} | {} | `{}` |",
            f.name, f.rows, f.bytes, f.fnv64
        );
    }
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "{} rows in total, a stratified sample of {} rows in the source bank.",
        m.rows, m.source.rows
    );
    let _ = writeln!(s);
    let _ = writeln!(s, "## Splits");
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "The split is the one the source row carries, not one this command assigns, so the three files can interleave in time."
    );
    let _ = writeln!(
        s,
        "`xcm-mmm pairs audit` is the check that a model is not reading a document in one split that it saw in another; the card does not claim the split is chronological."
    );
    let _ = writeln!(s);
    let _ = writeln!(s, "| split | rows | first day | last day |");
    let _ = writeln!(s, "| --- | --- | --- | --- |");
    for (name, c) in &m.splits {
        let _ = writeln!(
            s,
            "| {name} | {} | {} | {} |",
            c.rows, c.first_day, c.last_day
        );
    }
    let _ = writeln!(s);
    let _ = writeln!(s, "## Tasks");
    let _ = writeln!(s);
    let _ = writeln!(s, "| task | rows |");
    let _ = writeln!(s, "| --- | --- |");
    for (task, n) in &m.tasks {
        let _ = writeln!(s, "| {task} | {n} |");
    }
    let _ = writeln!(s);
    let _ = writeln!(s, "## Years");
    let _ = writeln!(s);
    let _ = writeln!(s, "| year | rows |");
    let _ = writeln!(s, "| --- | --- |");
    for (year, n) in &m.years {
        let _ = writeln!(s, "| {year} | {n} |");
    }
    let _ = writeln!(s);
    let _ = writeln!(s, "## Checks");
    let _ = writeln!(s);
    for c in &m.checks {
        let _ = writeln!(s, "- {c}");
    }
    let _ = writeln!(s);
    let _ = writeln!(s, "## Provenance");
    let _ = writeln!(s);
    let _ = writeln!(s, "- source: `{}`", m.source.path);
    let _ = writeln!(
        s,
        "- source rows: {}, {} bytes, fnv64 `{}`",
        m.source.rows, m.source.bytes, m.source.fnv64
    );
    let _ = writeln!(
        s,
        "- source days: {} to {}",
        m.source.first_day, m.source.last_day
    );
    let _ = writeln!(
        s,
        "- policy: budget {}, seed {}, cap {} bytes",
        m.config.budget, m.config.seed, m.config.cap_bytes
    );
    let _ = writeln!(s, "- built at: {}", m.built_at);
    let _ = writeln!(s);
    let _ = writeln!(s, "## Rebuild");
    let _ = writeln!(s);
    let _ = writeln!(s, "```");
    let _ = writeln!(
        s,
        "xcm-mmm dataset build --input <bank.jsonl> --out data/{} --budget {} --seed {}",
        m.folder, m.config.budget, m.config.seed
    );
    let _ = writeln!(s, "xcm-mmm dataset check --dir data/{}", m.folder);
    let _ = writeln!(s, "```");
    let _ = writeln!(s);
    let _ = writeln!(s, "## Limits");
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "Outcomes are forward returns measured over the label window, so the rows inherit the survivorship and coverage limits of the source feed."
    );
    let _ = writeln!(
        s,
        "The sample is not the bank: a model fitted here has seen one slice of the mined pairs, and the card states both counts rather than implying they match."
    );
    let _ = writeln!(
        s,
        "Nothing here is investment advice, and the news text is quoted under the source terms rather than relicensed."
    );
    s
}
